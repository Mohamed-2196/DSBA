// Writes src/ui/icons/glyphs/ from the brand's icon files (docs/design/deskmates/brand/icons/{nav,ui}/*.svg): one
// module per icon, and index.ts naming them all (the build puts them in one chunk, see vite.config.ts):
//
//   node scripts/icons.mjs
//
// Each icon becomes a list of parts, one per <path>, tagged with how it is painted:
//   l  a line (currentColor stroke)        h  the heavy line (the magnifier's handle)
//   t  the tinted body (--icon-tint)       p  a paper part (--icon-paper)
//   f  a dot or solid mark (currentColor fill, no stroke)
// The active files have the same geometry with a heavier stroke, so only the default files are read; <Icon active>
// draws the heavier stroke. Run it again whenever the brand's icons change, then npx prettier --write the output.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(web, '../docs/design/deskmates/brand/icons');
const out = join(web, 'src/ui/icons/glyphs');
const HEADER = "// Generated by scripts/icons.mjs from docs/design/deskmates/brand/icons. Don't edit by hand.\n";
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
// The nav set and the UI set both have a "more"; the nav one (three tinted dots) is the tab bar's.
const exportName = (set, name) => (set === 'nav' && name === 'more' ? 'moreTab' : camel(name));

function kindOf(attrs) {
  if (/stroke="none"/.test(attrs)) return 'f';
  if (/var\(--icon-tint/.test(attrs)) return 't';
  if (/var\(--icon-paper/.test(attrs)) return 'p';
  if (/stroke-width="2\.75"/.test(attrs)) return 'h';
  return 'l';
}

const seen = new Set();
for (const set of ['nav', 'ui']) {
  for (const file of readdirSync(join(source, set)).sort()) {
    if (!file.endsWith('.svg') || file.endsWith('-active.svg')) continue;
    const name = exportName(set, file.slice(0, -4));
    if (seen.has(name)) throw new Error(`Two icons are called ${name}`);
    seen.add(name);
    const svg = readFileSync(join(source, set, file), 'utf8');
    const parts = [...svg.matchAll(/<path([^>]*)\/>/g)].map(([, attrs]) => {
      const d = /\sd="([^"]+)"/.exec(attrs)?.[1];
      if (!d) throw new Error(`${set}/${file}: a path without d`);
      return `['${kindOf(attrs)}', '${d}']`;
    });
    writeFileSync(
      join(out, `${name}.ts`),
      `${HEADER}import type { Glyph } from '../glyph';\n\nexport const ${name}: Glyph = [${parts.join(', ')}];\n`,
    );
  }
}
const names = [...seen].sort();
writeFileSync(join(out, 'index.ts'), HEADER + names.map((n) => `export { ${n} } from './${n}';`).join('\n') + '\n');
console.log(`Wrote ${seen.size} icons to ${out}`);
