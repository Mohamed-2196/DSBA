def snowflake():
    arms, twigs = [], []
    for k in range(6):
        a = math.radians(-90 + 60 * k)
        ex, ey = 12 + 8.6 * math.cos(a), 12 + 8.6 * math.sin(a)
        arms.append(f'M12 12L{n(ex)} {n(ey)}')
        bx, by = 12 + 5.6 * math.cos(a), 12 + 5.6 * math.sin(a)
        for s in (-1, 1):
            b = a + s * math.radians(42)
            twigs.append(f'M{n(bx)} {n(by)}L{n(bx + 2.6 * math.cos(b))} {n(by + 2.6 * math.sin(b))}')
    return ''.join(arms) + ''.join(twigs)


