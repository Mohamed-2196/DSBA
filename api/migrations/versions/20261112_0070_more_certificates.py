def added(doc: dict[str, Any]) -> dict[str, Any] | None:
    """The document with the fields and the new certificates, or None when nothing changes."""
    certs = doc.get("certs")
    if not isinstance(certs, list):
        return None
    out = [
        {**c, "field": FIELDS[c["id"]]} if isinstance(c, dict) and c.get("id") in FIELDS and not c.get("field") else c
        for c in certs
    ]
    ids = {c.get("id") for c in out if isinstance(c, dict)}
    urls = {c.get("url") for c in out if isinstance(c, dict)}
    out += [c for c in NEW if c["id"] not in ids and c["url"] not in urls]
    if out == certs:
        return None
    return {**doc, "certs": out}


